/** @protects Codex pairing, model/reasoning settings, connection recovery and unified article requests. */
import assert from 'node:assert/strict';
import { bootWebApp } from '../support/web-app-harness.mjs';
import { installBridgeFetchStub } from '../support/bridge-browser-fixture.mjs';
import { MOCK_STATE } from '../support/provider-mock.mjs';
import { selectVisibleText } from '../support/visible-selection.mjs';
const app = await bootWebApp();
try {
  const context = await app.browser.newContext();
  await installBridgeFetchStub(context);
  const page = await context.newPage();
  await page.goto(app.baseUrl, { waitUntil: 'domcontentloaded' });
  await page.click('#blank-start-setup');
  await page.waitForSelector('#bridge-pairing-token');
  assert.match(await page.locator('#settings-panel').innerText(), /Backend\s+Codex/);
  await page.fill('#bridge-pairing-token', 'https://rabbithole.ing/#bridge=paired-token');
  await page.click('#bridge-pair');
  await page.waitForFunction(() => window.__bridgeStub.requests.some((request) => request.kind === 'events' && request.authorization === 'Bearer paired-token'));
  await page.evaluate((state) => window.__bridgeStub.push(state), MOCK_STATE);
  await page.waitForSelector('.bridge-surface[data-state="ready"] #bridge-model');
  await page.click('[data-reasoning="high"]');
  let stored = await page.evaluate(() => JSON.parse(localStorage.getItem('rh-web-settings')));
  assert.equal(stored.backend, 'codex'); assert.equal(stored.model, 'gpt-fake'); assert.equal(stored.reasoning, 'high');
  await page.click('#bridge-model');
  await page.click('.model-option[data-value="gpt-text"]');
  assert.equal(await page.locator('[data-reasoning="medium"]').getAttribute('aria-pressed'), 'true');
  await page.click('#bridge-model'); await page.click('.model-option[data-value="gpt-fake"]');
  await page.click('#restart-bridge');
  await page.waitForFunction(() => window.__bridgeStub.requests.some((request) => request.kind === 'restart'));
  assert.equal(await page.locator('#restart-bridge').getAttribute('aria-busy'), 'true');
  await page.waitForSelector('#restart-bridge:not([disabled])');
  await page.waitForSelector('.bridge-surface[data-state="ready"]');
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('rh-web-settings')).token), 'paired-token');
  await page.click('#complete-model-setup');
  await page.waitForSelector('#settings-sheet', { state: 'detached' });
  await page.evaluate(() => window.__bridgeStub.queueGeneration({ search: true, text: '# Codex search\n\nFound [Example](https://example.com/result).' }));
  await page.click('#blank-start-new'); await page.click('#composer-path-ask');
  await page.fill('#composer-input', 'Search current sources'); await page.click('#composer-primary');
  await page.locator('.shimmer-text').filter({ hasText: 'Searching the web' }).first().waitFor();
  await page.evaluate(() => window.__bridgeStub.finishSearch());
  await page.locator('.card.root', { hasText: 'Found Example.' }).waitFor();
  assert.equal(await page.locator('.card.root .origin-question').innerText(), 'Search current sources',
    'a root Ask answer shows its complete original prompt');
  await page.waitForFunction(async () => {
    const hole = await window.__rabbitholeTest.readStoredHole(); return hole?.nodes.find((node) => node.id === hole.root_id)?.extensions.backend_conversation;
  });
  const root = await page.evaluate(async () => { const hole = await window.__rabbitholeTest.readStoredHole(); return hole.nodes.find((node) => node.id === hole.root_id); });
  let requests = await page.evaluate(() => window.__bridgeStub.requests.filter((request) => request.kind === 'generate'));
  assert.equal(requests[0].body.backend, 'codex'); assert.equal(requests[0].body.input.kind, 'explain');
  assert.equal(requests[0].body.input.question, 'Search current sources');
  await page.evaluate(() => window.__bridgeStub.queueGeneration({ text: '# Whole follow-up\n\nWhole follow-up completed.' }));
  await page.locator('.card.root .nc-handle').evaluate((button) => button.click());
  await page.fill('.card.root .nc-inner textarea', 'Whole article question');
  await page.locator('.card.root .nc-inner [data-commit="ask"]').click();
  await page.locator('.card:not(.root)', { hasText: 'Whole follow-up completed.' }).waitFor();
  await page.evaluate(() => window.__bridgeStub.queueGeneration({ text: '# Selection follow-up\n\nSelection follow-up completed.' }));
  await selectVisibleText(page, { text: 'Found', rootSelector: '.card.root .doc-content' });
  await page.fill('#ask-text', 'Selected article question'); await page.locator('#ask [data-commit="ask"]').click();
  await page.locator('.card:not(.root)', { hasText: 'Selection follow-up completed.' }).waitFor();
  requests = await page.evaluate(() => window.__bridgeStub.requests.filter((request) => request.kind === 'generate'));
  assert.deepEqual(requests[1].body.sourceSession, root.extensions.backend_conversation);
  assert.deepEqual(requests[2].body.sourceSession, root.extensions.backend_conversation);
  assert.equal(requests[1].body.input.question, 'Whole article question');
  assert.equal(requests[2].body.input.selected_text, 'Found');
  assert.ok(requests.every((request) => request.authorization === 'Bearer paired-token'));
  await page.click('#t-settings'); await page.click('[data-settings-section="model"]');
  await page.evaluate(() => window.__bridgeStub.kill());
  await page.waitForSelector('.bridge-surface[data-state="bridge_down"]');
  await page.evaluate((state) => window.__bridgeStub.restart(state), MOCK_STATE);
  await page.waitForSelector('.bridge-surface[data-state="ready"]', { timeout: 20000 });
  await context.close();
  const shared = await app.browser.newContext(); await installBridgeFetchStub(shared);
  const waiting = await shared.newPage(); await waiting.goto(app.baseUrl);
  await waiting.click('#blank-start-setup'); await waiting.waitForSelector('#bridge-pairing-token');
  const pairing = await shared.newPage(); await pairing.goto(`${app.baseUrl}/#bridge=linked-token`);
  await waiting.waitForFunction(() => window.__bridgeStub.requests.some((request) => request.kind === 'events' && request.authorization === 'Bearer linked-token'));
  await waiting.evaluate((state) => window.__bridgeStub.push(state), MOCK_STATE);
  await waiting.waitForSelector('.bridge-surface[data-state="ready"]');
  assert.equal(await pairing.evaluate(() => location.hash.includes('bridge=')), false);
  await shared.close();
  console.log('ok Model setup: pairing, choices, restart/reconnect, native root/sibling requests and cross-tab pairing');
} finally { await app.close(); }
