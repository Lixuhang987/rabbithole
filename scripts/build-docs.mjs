async function excerpt(relativePath, marker, lines) {
  const source = await fs.readFile(path.join(root, relativePath), "utf8");
  const all = source.split("\n");
  const start = Math.max(0, all.findIndex((line) => line.includes(marker)));
  return all.slice(start, start + lines).join("\n").replace(/```/g, "` ` `");
}

async function readTestPurposes(files) {
  const result = [];
  const invalid = [];
  for (const file of files) {
    const source = await fs.readFile(path.join(root, file), "utf8");
    const match = source.match(/^\/\*\* @protects (.+?) \*\/\r?\n/);
    if (!match) invalid.push(file);
    else result.push({ file, purpose: match[1] });
  }
  if (invalid.length) throw new Error(`Tests missing an opening @protects docblock:\n${invalid.join("\n")}`);
  return result.sort((a, b) => a.file.localeCompare(b.file));
}

async function scanDocumentPaths() {
  const docs = ["README.md", "AGENTS.md", "CONTRIBUTING.md", ...await filesUnder("docs", (name) => name.endsWith(".md"))];
  const missing = [];
  for (const document of docs) {
    const source = await fs.readFile(path.join(root, document), "utf8");
    if (document.startsWith("docs/proposals/") || document === "docs/plans/codex-node-thread-fork.md") continue; // Historical paths describe retired implementations.
    for (const candidate of documentedPaths(source)) {
      const normalized = candidate.replace(/^\.\//, "").replace(/:(?:L)?\d+(?:-\d+)?$/, "").replace(/[),.;:]$/, "");
      if (!normalized || normalized.includes("*") || normalized.includes("{") || normalized.includes("<")) continue;
      if (!await exists(path.resolve(root, normalized))) missing.push(`${document}: \`${candidate}\``);
    }
  }
  return [...new Set(missing)].sort();
}

function documentedPaths(source) {
  const known = /^(?:\.\.?\/|src\/|test\/|scripts\/|docs\/|dist\/|web\/|website\/|workers\/|bin\/|policy\/|\.github\/|package\.json(?:$|:)|README\.md(?:$|:)|AGENTS\.md(?:$|:)|CONTRIBUTING\.md(?:$|:)|LICENSE(?:$|:)|THIRD_PARTY_NOTICES\.md(?:$|:))/;
  const inline = [...source.matchAll(/`([^`\n]+)`/g)].map((match) => match[1].trim()).filter((value) => known.test(value));
  const code = [...source.matchAll(/(?:^|[\s"'(])((?:src|test|scripts|docs|dist|web|website|workers|bin|policy|\.github)\/[A-Za-z0-9_./-]+\.(?:js|mjs|md|json|css|html|toml|ya?ml))/gm)]
    .map((match) => match[1]);
  return [...inline, ...code];
}

async function filesUnder(relativeDirectory, predicate) {
  const base = path.join(root, relativeDirectory);
  const found = [];
  async function walk(directory) {
    for (const entry of await fs.readdir(directory, { withFileTypes: true })) {
      const full = path.join(directory, entry.name);
      if (entry.isDirectory()) await walk(full);
      else if (entry.isFile() && predicate(entry.name)) found.push(path.relative(root, full).split(path.sep).join("/"));
    }
  }
  await walk(base);
  return found.sort();
}

async function exists(target) {
  try { await fs.access(target); return true; } catch { return false; }
}
